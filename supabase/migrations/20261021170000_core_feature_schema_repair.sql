-- Additive fixes for tables and columns already used by shipped StudyBud flows.
-- This migration intentionally does not change RLS on existing tables. Those policies
-- require a separate, reviewed rollout because some legacy tasks have no owner.
begin;

alter table public.atoms add column if not exists notes text;
alter table public.atoms add column if not exists time text;
alter table public.logs add column if not exists mood text;
alter table public.logs add column if not exists duration integer;
alter table public.logs add column if not exists time text;

create table if not exists public.focus_sessions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category text,
  duration_seconds integer,
  mode text
);
alter table public.focus_sessions enable row level security;
drop policy if exists focus_sessions_select_owner on public.focus_sessions;
create policy focus_sessions_select_owner on public.focus_sessions
  for select using ((select auth.uid()) = user_id);
drop policy if exists focus_sessions_insert_owner on public.focus_sessions;
create policy focus_sessions_insert_owner on public.focus_sessions
  for insert with check ((select auth.uid()) = user_id);
drop policy if exists focus_sessions_update_owner on public.focus_sessions;
create policy focus_sessions_update_owner on public.focus_sessions
  for update using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists focus_sessions_delete_owner on public.focus_sessions;
create policy focus_sessions_delete_owner on public.focus_sessions
  for delete using ((select auth.uid()) = user_id);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text,
  last_name text,
  nickname text,
  age integer,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
drop policy if exists profiles_select_owner on public.profiles;
create policy profiles_select_owner on public.profiles
  for select using ((select auth.uid()) = id);
drop policy if exists profiles_insert_owner on public.profiles;
create policy profiles_insert_owner on public.profiles
  for insert with check ((select auth.uid()) = id);
drop policy if exists profiles_update_owner on public.profiles;
create policy profiles_update_owner on public.profiles
  for update using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
drop policy if exists profiles_delete_owner on public.profiles;
create policy profiles_delete_owner on public.profiles
  for delete using ((select auth.uid()) = id);

create index if not exists atoms_user_created_idx on public.atoms(user_id, created_at desc);
create index if not exists logs_user_date_idx on public.logs(user_id, date_logged desc);
create index if not exists study_assignments_user_created_idx on public.study_assignments(user_id, created_at desc);
create index if not exists study_practice_logs_user_created_idx on public.study_practice_logs(user_id, created_at desc);
create index if not exists study_reviews_user_due_idx on public.study_reviews(user_id, next_review_date);
create index if not exists mind_logs_user_created_idx on public.mind_logs(user_id, created_at desc);
create index if not exists mind_offload_user_created_idx on public.mind_offload_items(user_id, created_at desc);
create index if not exists mind_wins_user_created_idx on public.mind_wins(user_id, created_at desc);
create index if not exists tasks_user_created_idx on public.tasks(user_id, created_at desc);

commit;
